/**
 * @file ellipse.c
 * @brief Elliptic filter coefficients and processing for bashfest~.
 * Modernized for Max 8/9 with anti-denormal protection and input validation.
 */

#include "bashfest.h"
#include <math.h>

float ellipse(float x, LSTRUCT *eel, int nsects, float xnorm)
{
    float op;

    for (int m = 0; m < nsects; m++) {
        op = x + eel[m].c0 * eel[m].ps0 + eel[m].c2 * eel[m].ps1
               - eel[m].c1 * eel[m].ps2 - eel[m].c3 * eel[m].ps3;

        // Anti-denormal protection: clamp subnormal filter states to zero
        if (fabsf(op) < 1.0e-15f) {
            op = 0.0f;
            eel[m].ps0 = 0.0f;
            eel[m].ps1 = 0.0f;
            eel[m].ps2 = 0.0f;
            eel[m].ps3 = 0.0f;
        } else {
            eel[m].ps1 = eel[m].ps0;
            eel[m].ps0 = x;
            eel[m].ps3 = eel[m].ps2;
            eel[m].ps2 = op;
        }

        x = op;
    }

    return (x * xnorm);
}

void ellipset(float *list, LSTRUCT *eel, int *nsects, float *xnorm)
{
    if (!list || !eel || !nsects || !xnorm) return;

    /* The first argument in the list is the number of sections */
    int n = (int)list[0];
    if (n <= 0 || n > MAXSECTS) {
        if (n > MAXSECTS) {
            error("sorry, only configured for %d sections", MAXSECTS);
        }
        *nsects = 0;
        *xnorm = 1.0f;
        return;
    }

    *nsects = n;
    int i = 1;
    for (int m = 0; m < n; m++) {
        eel[m].c0 = list[i++];
        eel[m].c1 = list[i++];
        eel[m].c2 = list[i++];
        eel[m].c3 = list[i++];
        eel[m].ps0 = 0.0f;
        eel[m].ps1 = 0.0f;
        eel[m].ps2 = 0.0f;
        eel[m].ps3 = 0.0f;
    }
    *xnorm = list[i];
}

